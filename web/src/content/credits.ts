export type CreditId = keyof typeof CREDITS;

export function getCredit(id: string): CreditEntry | null {
  return (CREDITS as Record<string, CreditEntry>)[id] ?? null;
}

/** Map layers carry their own citation in layers.json (`source_citation` → LayerEntry.source). */
export function layerCredit(source: string, derived: boolean): CreditEntry {
  return {
    credit: source,
    what: derived ? 'Map layer derived by the LUMEN terrain pipeline' : 'Map layer',
    license: derived ? 'Derived product; see Methodology' : 'See source',
    sourceUrl: null,
    owner: 'Shiva Shakthi',
  };
}
