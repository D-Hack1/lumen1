// Owner: Abhinav
// Credits content for imagery shown in the app body (Lens body images, map layers, Quick-Start thumbnails).
// One entry per asset; `CreditLine` (ui/CreditLine.tsx) renders it. Every entry here is also listed in
// docs/credits_frontend.md. Rules (guide §3.3): local files only, NASA/LROC preferred, never a logo or insignia,
// never an AI-generated image presented as real; ISRO imagery only with its terms recorded in `license`.
//
// `sourceUrl: null` = the asset owner has not recorded the exact source page yet — the line still shows the credit,
// and docs/credits_frontend.md lists it as an open item. Do not invent URLs here.

export interface CreditEntry {
  /** Short credit shown on the image foot, e.g. "NASA/SDO". */
  credit: string;
  /** What the image is (for the tooltip / screen readers). */
  what: string;
  license: string;
  sourceUrl: string | null;
  /** Asset owner (who adds/changes the file). */
  owner: 'Abhinav' | 'Ebin' | 'Nived' | 'Gowri' | 'Shiva Shakthi';
}

